// БОЛЕЗНЬ (Ф1): от чего хомячок простужается, сколько болеет и что при этом нельзя. Только таблицы и чистый расчёт.
//
// Как это устроено:
//   - за день хомячок может «неосторожничать» (CARELESS): долго гулять в холод без тёплой вещи, купаться или нырять
//     в море в холодные месяцы, мокнуть под дождём без куртки и сапожек. Каждая неосторожность прибавляет к шансу
//     заболеть этой ночью; есть и крошечный шанс «просто так» (HEALTH.base);
//   - решение принимается при смене дня (сон) и зависит только от номера нового дня, имени хомячка и того, что было
//     за день (nightHealth): перезагрузка страницы кубик не перебрасывает, а dev/balance.js считает теми же функциями;
//   - болеет самое большее HEALTH.days дня: утром следующего выздоравливает сама; доктор в больнице лечит сразу;
//   - после выздоровления HEALTH.immune дней не болеет, в новой игре — первые HEALTH.grace дня.
// Что при этом происходит в игре (медленнее ходит, нельзя работать и купаться, чихает) — features/health.js;
// цена приёма у доктора — DOCTOR_FEE в data/economy.js.
import { monthOfDay } from './calendar.js';
import { dayRoll } from './stock.js';

export const HEALTH = {
  base: 0.02, // шанс «просто так» за ночь
  max: 0.45, // больше этого шанс не бывает, сколько ни неосторожничай: заболеть каждую ночь нельзя
  days: 2, // болеет не дольше 2 дней: заболела утром дня D — утром дня D + 2 здорова сама
  immune: 4, // после выздоровления столько дней не болеет (заболеть снова можно в ночь на день выздоровления + 4)
  grace: 3, // в новой игре первые 3 дня (0, 1, 2) не болеет
  slow: 0.7, // простуженная ходит медленнее (×0,7); тёплый чай или горячий шоколад возвращают обычный шаг на день
  warnMin: 20, // через столько игровых минут на холоде (под дождём) — добрая подсказка «надень тёплое»
  outMin: 60, // а через столько — это уже неосторожность (игровая минута — 0,6 с)
};

/** Холодные месяцы (поздняя осень и зима): на улице нужна тёплая вещь, море ледяное. 0 — январь. */
export const COLD_MONTHS = [10, 11, 0, 1];
export const isColdMonth = (month) => COLD_MONTHS.includes(month);

/** Неосторожности за день: id — отметка дня (dayFlags.careless[id]); risk — прибавка к шансу заболеть ночью. */
export const CARELESS = {
  sea: {
    risk: 0.2,
    morning: 'Вчера ты купалась в ледяном море.',
    tip: 'Зимой и поздней осенью в море не купаются — вода ледяная. Плавай летом или в бассейне!',
  },
  cold: {
    risk: 0.15,
    morning: 'Вчера ты долго гуляла на морозе без тёплых вещей.',
    tip: 'В холод надевай шапку, тёплую куртку, кофту или шарф.',
  },
  rain: {
    risk: 0.12,
    morning: 'Вчера ты промокла под дождём.',
    tip: 'В дождь надевай куртку или резиновые сапожки.',
  },
};
/** Если заболела «просто так». */
export const JUST_BECAUSE = 'Так бывает: иногда простужаются и просто так.';

/** Шанс заболеть ночью после дня с такими неосторожностями ({ sea: 1, cold: 1 }). */
export function sickChance(careless = {}) {
  let p = HEALTH.base;
  for (const id of Object.keys(CARELESS)) if (careless[id]) p += CARELESS[id].risk;
  return Math.min(HEALTH.max, p);
}
/** Из-за чего заболела: самая «рискованная» неосторожность дня; 'none' — просто так. */
export function sickCause(careless = {}) {
  let best = 'none',
    r = 0;
  for (const [id, c] of Object.entries(CARELESS))
    if (careless[id] && c.risk > r) {
      best = id;
      r = c.risk;
    }
  return best;
}

/**
 * Что случится этой ночью. day — номер наступающего дня; sick — { since, cause } или null; immuneUntil — с какого
 * дня снова можно заболеть; careless — неосторожности прошедшего дня; key — своё у каждой игры (имя хомячка), чтобы
 * «просто так» болели не все хомячки в один и тот же день.
 * → { recover: true } — утром здорова сама; { fall: причина } — заболела; {} — ничего.
 */
export function nightHealth({ day, sick, immuneUntil = 0, careless = {}, key = '' }) {
  if (sick) return day >= sick.since + HEALTH.days ? { recover: true } : {};
  if (day < Math.max(HEALTH.grace, immuneUntil)) return {};
  return dayRoll(day, 'sick:' + key) < sickChance(careless) ? { fall: sickCause(careless) } : {};
}

// ---------- одежда: тепло ли и не промокнет ли ----------
// outfit — наряд с объектами вещей (как в playerLook().outfit).
/** Тёплая вещь: из коллекции «тёплое» (season: 'cold') или с тегом warm. */
const warm = (c) => !!c && (c.season === 'cold' || c.tags.includes('warm'));
/** Тепло ли одета: тёплая вещь на голове (шапка, наушники), на теле (куртка, кофта, тёплое платье) или шарф. */
export const dressedWarm = (outfit) => ['head', 'body', 'acc'].some((k) => warm(outfit[k]));
const JACKETS = ['jacketW', 'jacketA', 'jacketS'];
/** Не промокнет под дождём: куртка, дождевик или резиновые сапожки (вещи с тегом rain на голове, теле, ногах). */
export const dressedForRain = (outfit) =>
  (!!outfit.body && JACKETS.includes(outfit.body.kind)) ||
  ['head', 'body', 'feet'].some((k) => !!outfit[k] && (outfit[k].season === 'rain' || outfit[k].tags.includes('rain')));
/** Тёплая ли вещь из шкафа (шапка, наушники, куртка, кофта, тёплое платье, шарф) — то, что засчитывает dressedWarm. */
export const isWarmItem = (c) => !!c && ['head', 'body', 'acc'].includes(c.slot) && warm(c);
/** Проверки наряда по имени — для шага задания «приди в тёплом» ({ dress: 'warm' } в data/quests.js). */
export const DRESS = { warm: dressedWarm, rain: dressedForRain };
/** Холодно ли сегодня на улице без тёплой вещи (поздняя осень и зима). */
export const coldDay = (day) => isColdMonth(monthOfDay(day));

