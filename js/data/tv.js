// ---------- кулинарное шоу «У плиты» ----------
// Выпуск — раз в 3–4 дня: дни, у которых остаток от деления на 7 — 0 или 3 (через 3, потом через 4 дня и снова).
// Весь день в эфире (с повторами). Досмотрела до конца — узнала рецепт выпуска, если его ещё нет.
/** Сколько секунд настоящего времени идёт выпуск (до рецепта). */
export const COOK_SHOW_SEC = 22;
/** Идёт ли «У плиты» в день day. */
export const cookShowOn = (day) => day % 7 === 0 || day % 7 === 3;
/** Ближайший день выпуска, начиная с day (сам day — если сегодня выпуск). */
export function nextCookShow(day) {
  let d = day;
  while (!cookShowOn(d)) d++;
  return d;
}
/** Номер выпуска (растёт от выпуска к выпуску): с него начинается очередь блюд. */
export const cookShowNo = (day) => Math.floor(day / 7) * 2 + (day % 7 === 3 ? 1 : 0);
