//
// Задание:
//   id        имя (попадает в сохранение — не переименовывать)
//   npc       кто даёт задание (id из data/npcs.js); у него над головой «!», пока задание можно взять
//   icon, title, story   значок, название и короткая история для журнала
//   when(s)   когда задание можно взять (s — сохранение); без when — сразу
//   lines     что говорит житель: offer — предлагает, accept — согласились, wait — как дела (по шагам: { шаг: текст }
//             или одна строка), done — сдали задание; later — «потом» на предложение
//   steps     цепочка шагов. Шаг — одно понятное действие:
//               { on: 'событие', n, if: { поле: значение }, min: { поле: число }, distinct: 'поле' }
//                   сделать что-то: событие из core/events.js случилось n раз (с такими полями); distinct —
//                   считать только разные значения поля (три разных жителя)
//               { bring: { bag, id } | { bag, kind, distinct: true }, n }
//                   принести: в рюкзаке n штук (или n разных находок этого вида); отдаются, когда задание сдают
//               { talk: 'житель' }   поговорить с жителем (над ним «?»); последний шаг — сдать задание
//             У шага: text — что сделать (для журнала), where — куда показывает звёздочка (здание, место, точка
//             локации, 'npc:<житель>' или 'herb' — ближайшее место для гербария), hint — «куда идти» словами.
//             Шаги «сделать» считаются с той минуты, как задание взято, в любом порядке; «поговорить» — когда всё,
//             что до него, уже сделано. Текущий шаг — первый несделанный.
//   reward    награда: coins (монеты — QUEST_COINS в economy.js), sticker (id из EXTRA_STICKERS), clothes (вещь;
//             если она уже есть — монеты QUEST_GIFT_COINS), open (id места из LANDS — data/places.js)
