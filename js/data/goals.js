// КВЕСТЫ: единый порядок. Квест — любое дело, к которому игру может вести звёздочка: задание жителя (сюжетное,
// вводное, «дверное»), праздник сегодня, письмо дня. Список квестов собирает features/goals.js, а ПОРЯДОК — только
// здесь, в одной функции goalRank: по нему квесты стоят в журнале и по нему же выбирается следующий активный квест,
// когда прежний закончен. Чистые функции без состояния — проверяются без браузера (node dev/test_goals.js).
//
// Квест для порядка — { id, group, started, since }:
//   group   — 'story' (задание жителя из журнала), 'holiday' (праздник сегодня), 'routine' (рутина: письмо дня);
//   started — уже начат: задание взято, на празднике что-то сделано, по письму что-то собрано;
//   since   — день, когда взят (у заданий жителей; раньше взят — раньше в списке).

/** Виды квестов — от самых интересных к рутине. */
export const GOAL_GROUPS = ['story', 'holiday', 'routine'];

/**
 * МЕСТО КВЕСТА В ОБЩЕМ ПОРЯДКЕ: чем меньше число, тем раньше (интереснее). Решение заказчика:
 *   0–2  УЖЕ НАЧАТЫЕ — в начале: бросать начатое обиднее всего. Среди них — тот же порядок видов:
 *        0 — задание жителя, 1 — праздник, 2 — письмо дня;
 *   3    задания жителей, которые ещё не взяты (житель с «!» ждёт) — сюжет интереснее всего остального;
 *   4    праздник сегодня (ещё ничего не сделано) — он всего на один день, но это не сюжет;
 *   5    РУТИНА — в самом конце: письмо дня (непрочитанное или прочитанное, но не начатое).
 * Новый вид квеста — новая группа в GOAL_GROUPS; больше нигде порядок менять не надо.
 */
export function goalRank(g) {
  const kind = Math.max(0, GOAL_GROUPS.indexOf(g.group));
  return g.started ? kind : GOAL_GROUPS.length + kind;
}

/** Квесты по порядку (новый список). При равном месте — взятый раньше, потом — как стояли (порядок описаний). */
export function sortGoals(list) {
  return list
    .map((g, i) => ({ g, i, r: goalRank(g) }))
    .sort((a, b) => a.r - b.r || (a.g.since || 0) - (b.g.since || 0) || a.i - b.i)
    .map((x) => x.g);
}

/**
 * КАКОЙ КВЕСТ АКТИВЕН ДАЛЬШЕ. current — id активного квеста из сохранения (или null), list — квесты, которые сейчас
 * есть. Активный ещё в списке — остаётся он (сам квест никогда не меняется, пока не закончен: менять может только
 * игрок). Его нет (закончен, день прошёл, ничего не выбрано) — первый по порядку; квестов нет — null.
 */
export function nextGoal(current, list) {
  if (current && list.some((g) => g.id === current)) return current;
  const first = sortGoals(list)[0];
  return first ? first.id : null;
}
