// «Скоро открытие!» — временная заглушка для мест, которые уже стоят в городе, но ещё не открыты:
// агентство недвижимости, жилой дом с квартирой, бунгало, отель, тропа в лес, караван в пустыню.
// Место называет действие 'soon' с ключом: { do: 'soon', key: 'hotel' } или 'soon:hotel'.
// Когда занятие готово — у места просто меняют act на настоящее действие (locations/town.js).
import { sfx } from '../core/audio.js';
import { register } from '../core/registry.js';
import { toast } from '../ui/toast.js';

/** Что сказать у двери: ключ места → [название, добрая подсказка]. */
export const SOON = {
  realtor: ['Агентство «Свой домик»', 'Здесь будут продавать квартиры и домики. Копи монетки!'],
  home_apartment: ['Квартира в жилом доме', 'Её можно будет купить в агентстве «Свой домик».'],
  home_bungalow: ['Пляжное бунгало', 'Домик у самого моря с гамаком. Его можно будет купить!'],
  hotel: ['Отель «Морская звезда»', 'Маляры докрашивают номера — совсем скоро здесь встретят гостей.'],
  forest: ['Тропа в лес', 'Ворота пока закрыты. Говорят, Мята знает, как туда попасть…'],
  desert: ['Караван в пустыню', 'Автобус к барханам ещё не ходит. Буся что-то слышала про путешествие!'],
};

register(
  'soon',
  (p, ctx) => {
    const key = p.key || p.arg,
      [name, hint] = SOON[key] || [(ctx.building && ctx.building.name) || 'Это место', ''];
    sfx('tap');
    toast(`🚧 Скоро открытие! ${name}. ${hint}`.trim());
  },
  'заглушка «Скоро открытие!»: soon:<ключ места> или { key } — realtor, home_apartment, home_bungalow, hotel, forest, desert',
);
