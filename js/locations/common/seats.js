// МЕСТА ДЛЯ ОТДЫХА (этап 17а): предметы, на которые хомячок садится, ложится или качается.
//
//   bench: { solid: true, ...seat('sit', [[-11, 4, -11, 31], [11, 4, 11, 31]], { dx: 30, up: 44, down: 22 }), draw }
//
// seat(как, места, зона нажатия) добавляет виду предмета три поля:
//   seat: { how, spots }   how — поза: 'sit' (скамейка, бревно, пенёк, бортик фонтана), 'lie' (лежак, полотенце),
//                          'swing' (качели), 'hammock' (гамак), 'slide' (горка — съехать один раз);
//                          spots — [[dx, dy, ax, ay], …]: где нарисован отдыхающий (сдвиг от центра клетки предмета)
//                          и где он «стоит» на самом деле (ax, ay — клетка, куда можно встать: на неё он и встаёт,
//                          когда уходит). Мест у скамейки и качелей два — на второе иногда садится житель.
//   tap, use               зона нажатия и что делает подошедший хомячок (движок локаций, engine/topdown/scene.js):
//                          действие реестра 'relax' — занятие features/relax.js.
// Предмет без своего рисунка «занятого места» рисуется как обычно; качели прячут сиденье, на котором качаются
// (поле o.busy предмета — номер места + 1; его ставит и снимает features/relax.js).
import { run } from '../../core/registry.js';
import { cal } from '../../core/state.js';

/** Поля вида предмета «на него можно присесть»: seat, tap, use; summer: true — зимой предмет убран (гамак, полотенце). */
export function seat(how, spots, tap, { summer = false } = {}) {
  const k = { seat: { how, spots }, tap, use: (sc, o) => run('relax', { scene: sc, obj: o }) };
  if (summer) k.tapIf = () => cal().season !== 'winter';
  return k;
}
